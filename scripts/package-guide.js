// Run after installing the existing `three` dependency (npm ci), or pass its build file.
// This copies the existing guide; it does not maintain a second version of the instructions.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'android-glasses/app/src/main/assets/guide');
const phone = path.join(root, 'ios-companion/MLDemo/coupling.json');
const three = process.argv[2] || path.join(root, 'node_modules/three/build/three.min.js');
if (!fs.existsSync(three)) throw new Error('Install dependencies with npm ci, or pass a three@0.149.0 build file.');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'public/workflow-steps.js'), 'utf8'), context);
const job = context.window.WF_JOBS.coupling;
if (job.steps.length !== 8) throw new Error('Update the native guide protocol totals before packaging a changed step count.');
fs.mkdirSync(path.join(output, 'vendor'), { recursive: true });
for (const file of ['workflow3d.html', 'hud-layout.js', 'widget.js']) {
  fs.copyFileSync(path.join(root, 'public', file), path.join(output, file));
}
fs.copyFileSync(three, path.join(output, 'vendor/three.min.js'));
fs.copyFileSync(path.resolve(path.dirname(three), '../LICENSE'), path.join(output, 'vendor/THREE-LICENSE.txt'));
fs.copyFileSync(path.join(root, 'android-glasses/companion-client.js'), path.join(output, 'arwa-client.js'));
fs.writeFileSync(path.join(output, 'workflow-steps.js'), `// Generated by scripts/package-guide.js\nwindow.WF_JOBS = ${JSON.stringify({ coupling: job }, null, 2)};\nwindow.WF_STEPS = window.WF_JOBS.coupling.steps;\n`);
const guide = { id: 'coupling', version: 1, title: job.title,
  summary: 'Follow the existing motor-to-pump coupling guide, with animated 3D instructions on your glasses.', steps: job.steps };
fs.writeFileSync(phone, JSON.stringify(guide, null, 2) + '\n');
console.log('Packaged motor-coupling viewer for Android and guide metadata for iPhone.');
